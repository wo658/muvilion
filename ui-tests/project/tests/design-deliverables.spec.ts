import { expect, test } from '@playwright/test';
import { createDeliverableProject, openDeliverableProject } from '../../helpers/deliverables';

// Model output is deterministic in these regressions; project API/SQLite and WebGL captures are real.
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('muvilion.settings.language.v1', 'en'));
});

test('document generation, targeted Muse revision, real photos, reload and PDF', async ({ page, context }) => {
  test.setTimeout(180000);
  await page.route('**/api/plans/intent', route => route.fulfill({ json: { intent: 'planning', message: 'Updating the document.', brief: 'Set A1 fee to 1500000 KRW; preserve A2.' } }));
  const targets: unknown[] = [];
  await page.route('**/api/plans/planning', async route => {
    const body = route.request().postDataJSON(); targets.push(body.target);
    const content = structuredClone(body.content);
    const first = !content.sections[0].text;
    if (first) {
      content.title = 'Partner showcase · planning document';
      content.sections = content.sections.map((s: { id: string }) => ({ ...s, text: s.id === 'overview' ? 'A compact exhibition for brand encounters.' : 'A planned space for visitors. Confirm the venue conditions.' }));
      content.booths = content.booths.map((b: object) => ({ ...b, description: 'A brand experience booth.', circulation: 'Approach from the main aisle. Keep the frontage clear.' }));
    } else content.booths[0].fee = { amount: 1500000, currency: 'KRW', basis: 'Organizer planning assumption <script>window.injected=true</script>', includes: 'Counter and signage', tax: 'excluded' };
    await route.fulfill({ json: { content, summary: first ? 'Document created.' : 'A1 fee updated; A2 unchanged.', captureIds: first ? ['overview', 'A1', 'A2'] : [] } });
  });
  const project = await createDeliverableProject(page, true);
  await openDeliverableProject(page, project.id);
  await page.getByRole('button', { name: 'Planning document', exact: true }).click();
  const panel = page.getByTestId('planning-artifact');
  await expect(panel.locator('input, textarea, [contenteditable=true]')).toHaveCount(0);
  await panel.getByRole('button', { name: 'Create planning document', exact: true }).click();
  await expect(panel.locator('img')).toHaveCount(3, { timeout: 90000 });
  await expect(panel.getByRole('button', { name: 'Cancel', exact: true })).toHaveCount(0);
  const capture = await panel.locator('img').first().getAttribute('src');
  expect(capture).toMatch(/^data:image\/jpeg;base64,/);
  expect(capture!.length).toBeGreaterThan(10000);
  await expect.poll(async () => (await (await page.request.get(`/api/projects/${project.id}`)).json()).state.planningArtifacts?.[0]?.photos.length).toBe(3);
  const a1 = panel.locator('section').filter({ has: page.getByRole('heading', { name: 'A1 · Brand showcase', exact: true }) }).last();
  await a1.getByRole('button', { name: 'Ask Muse about this', exact: true }).click();
  await page.getByRole('textbox', { name: 'Ask Muse about your drawing' }).fill('Set this booth participation fee to 1500000 KRW, excluding tax.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(a1).toContainText('1,500,000');
  expect(targets.at(-1)).toBe('A1');
  const stored = () => page.request.get(`/api/projects/${project.id}`).then(r => r.json());
  await expect.poll(async () => (await stored()).state.planningArtifacts[0].content.booths[0].fee.amount).toBe(1500000);
  const state = (await stored()).state;
  expect(state.planningArtifacts[0].content.booths[1].fee.amount).toBeNull();
  expect(state.document).toEqual(project.state.document);
  await page.reload();
  await page.getByRole('button', { name: 'Planning document', exact: true }).click();
  await expect(panel.locator('img')).toHaveCount(3);
  await expect(panel).toContainText('1,500,000');
  await expect(panel.locator('script')).toHaveCount(0);
  const popupPromise = context.waitForEvent('page');
  await panel.getByRole('button', { name: 'Open planning PDF', exact: true }).click();
  const report = await popupPromise;
  await expect(report.getByRole('heading', { name: 'Participation guide', exact: true })).toBeVisible();
  await expect(report.locator('body')).toContainText('1,500,000');
  await expect.poll(() => report.locator('img').evaluateAll(images => images.every(i => (i as HTMLImageElement).complete && (i as HTMLImageElement).naturalWidth > 0))).toBe(true);
  expect((await report.pdf({ format: 'A4' })).subarray(0, 4).toString()).toBe('%PDF');
  await report.close();
  await panel.getByRole('button', { name: 'Undo document revision', exact: true }).click();
  await expect.poll(async () => (await stored()).state.planningArtifacts[0].content.booths[0].fee.amount).toBeNull();
});

test('failed and cancelled generation preserves the saved document; changed geometry requires refresh', async ({ page }) => {
  test.setTimeout(90000);
  const project = await createDeliverableProject(page);
  const content = { title: 'Saved planning', sections: ['overview', 'intent', 'circulation', 'operations', 'notes'].map(id => ({ id, text: 'Saved copy' })), booths: ['A1', 'A2'].map(id => ({ id, description: 'Booth', circulation: 'Review access', fee: { amount: null, currency: 'KRW', basis: '', includes: '', tax: 'unknown' } })) };
  await page.route('**/api/plans/planning', route => route.fulfill({ json: { content, summary: 'Created', captureIds: [] } }));
  await openDeliverableProject(page, project.id);
  await page.getByRole('button', { name: 'Planning document', exact: true }).click();
  const panel = page.getByTestId('planning-artifact');
  await panel.getByRole('button', { name: 'Create planning document', exact: true }).click();
  await expect(panel.getByRole('heading', { name: 'Saved planning', exact: true })).toBeVisible();
  await expect.poll(async () => (await (await page.request.get(`/api/projects/${project.id}`)).json()).state.planningArtifacts?.length).toBe(1);
  await page.route('**/api/plans/intent', route => route.fulfill({ json: { intent: 'planning', message: 'Revising', brief: 'Revise overview' } }));
  await page.unroute('**/api/plans/planning');
  await page.route('**/api/plans/planning', route => route.fulfill({ status: 502, json: { error: 'Muse could not revise the planning document. Try again.' } }));
  await page.getByRole('textbox', { name: 'Ask Muse about your drawing' }).fill('Revise overview');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(panel.getByRole('alert')).toBeVisible();
  await expect(panel.getByRole('heading', { name: 'Saved planning', exact: true })).toBeVisible();
  await page.unroute('**/api/plans/planning');
  let release!: () => void;
  const delayed = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/plans/planning', async route => {
    await delayed;
    await route.fulfill({ json: { content: { ...content, title: 'Cancelled replacement' }, summary: 'Late result', captureIds: [] } }).catch(() => {});
  });
  await page.getByRole('textbox', { name: 'Ask Muse about your drawing' }).fill('Try revising again');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Cancel', exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Cancel', exact: true }).click();
  release();
  await expect(panel.getByRole('button', { name: 'Cancel', exact: true })).toHaveCount(0);
  await expect(panel.getByRole('heading', { name: 'Saved planning', exact: true })).toBeVisible();
  const saved = await (await page.request.get(`/api/projects/${project.id}`)).json();
  saved.state.document.zones[0].width = 5;
  if (saved.state.drawings?.length) saved.state.drawings[0].document = saved.state.document;
  expect((await page.request.put(`/api/projects/${project.id}`, { data: saved })).ok()).toBe(true);
  await page.reload();
  await page.getByRole('button', { name: 'Planning document', exact: true }).click();
  await expect(panel).toContainText('This document still shows its saved version');
  await panel.getByRole('button', { name: 'Refresh dimensions & references', exact: true }).click();
  await expect(panel).toContainText('5 × 3 m');
  await expect(panel.getByRole('button', { name: 'Refresh dimensions & references', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await expect(panel).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addInitScript(() => localStorage.setItem('muvilion.settings.language.v1', 'ko'));
  await page.reload();
  await page.getByRole('button', { name: '기획문서', exact: true }).click();
  await expect(panel.getByRole('heading', { name: '참가 안내', exact: true })).toBeVisible();
  await expect(panel.locator('input, textarea, [contenteditable=true]')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await panel.getByRole('button', { name: 'Muse에게 이 부분 요청', exact: true }).first().click();
  await expect(page.getByRole('textbox')).toBeFocused();
});
